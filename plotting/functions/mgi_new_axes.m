function ax = mgi_new_axes(fig,position,cfg)
%MGI_NEW_AXES Axes at a position in inches with the manuscript style.
    ax = axes('Parent',fig,'Units','inches','Position',position, ...
        'FontName',cfg.figures.font,'FontSize',cfg.figures.fontSize, ...
        'TickDir','out','Box','off','LineWidth',0.5,'Color','none', ...
        'XColor','k','YColor','k','TickLength',[0.02 0.02],'Layer','top');
    hold(ax,'on');
end
