function fig = mgi_new_figure(cfg,width,height)
%MGI_NEW_FIGURE White figure of a fixed physical size (inches).
    fig = figure('Visible',cfg.figures.visible,'Color','w','Units','inches', ...
        'Position',[1 1 width height],'PaperUnits','inches', ...
        'PaperSize',[width height],'PaperPosition',[0 0 width height], ...
        'InvertHardcopy','off');
    if exist('OCTAVE_VERSION','builtin') == 0
        set(fig,'Renderer','painters');
    end
    set(fig,'DefaultAxesFontName',cfg.figures.font,'DefaultTextFontName',cfg.figures.font, ...
        'DefaultAxesFontSize',cfg.figures.fontSize,'DefaultTextFontSize',cfg.figures.fontSize);
end
